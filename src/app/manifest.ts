import type { MetadataRoute } from "next";
import { siteConfig } from "@/config/site";

export default function manifest(): MetadataRoute.Manifest {
  return {
    name: `${siteConfig.name} — ${siteConfig.tagline}`,
    short_name: siteConfig.name,
    description: siteConfig.description,
    start_url: "/",
    display: "standalone",
    background_color: "#f3f3f6",
    theme_color: "#6c47ff",
    /*
     * PNGs at the two sizes installers actually ask for, plus the vector for
     * anything that prefers one. `purpose: "maskable"` is deliberately absent:
     * the mark is a rounded tile with its own padding, and declaring it
     * maskable would let Android crop into the glyph.
     */
    icons: [
      { src: "/icon.svg", sizes: "any", type: "image/svg+xml" },
      { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
      { src: "/apple-icon", sizes: "180x180", type: "image/png" },
    ],
  };
}
